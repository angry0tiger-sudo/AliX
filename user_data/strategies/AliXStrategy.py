"""Conservative Freqtrade strategy scaffold with a fail-closed OHLCV gate.

No entry signals are generated by this scaffold. Strategy behavior must remain
paper/backtest-only until later phase gates explicitly approve otherwise.
"""

from __future__ import annotations

from typing import Any

from pandas import DataFrame

from services.data_quality.gate import (
    QualityReasonCode,
    QualityResult,
    QualityStatus,
    validate_candles,
)

try:
    from freqtrade.strategy import IStrategy  # type: ignore[import-not-found]
except ImportError:  # Allows lightweight static checks outside the Freqtrade runtime.

    class IStrategy:  # type: ignore[no-redef]
        pass


_TIMEFRAME_SECONDS = {
    "1m": 60,
    "3m": 180,
    "5m": 300,
    "15m": 900,
    "30m": 1800,
    "1h": 3600,
    "2h": 7200,
    "4h": 14400,
    "1d": 86400,
}


class AliXStrategy(IStrategy):  # type: ignore[misc]
    INTERFACE_VERSION = 3
    timeframe = "1h"
    can_short = False
    minimal_roi = {"0": 0.0}
    stoploss = -0.10
    trailing_stop = False
    process_only_new_candles = True
    startup_candle_count = 100

    def populate_indicators(
        self, dataframe: DataFrame, metadata: dict[str, Any]
    ) -> DataFrame:
        """Run the same OHLCV gate for backtest and runtime before features."""
        interval_seconds = _TIMEFRAME_SECONDS.get(self.timeframe)
        if interval_seconds is None:
            result = QualityResult(
                False,
                ("unsupported_timeframe",),
                QualityStatus.REJECTED,
                (QualityReasonCode.UNSUPPORTED_TIMEFRAME,),
            )
        else:
            rows = [
                {str(key): value for key, value in row.items()}
                for row in dataframe.to_dict(orient="records")
            ]
            result = validate_candles(
                rows,
                expected_interval_seconds=interval_seconds,
            )
        dataframe["alix_data_quality_valid"] = result.passed
        dataframe.attrs["alix_data_quality"] = {
            "status": result.status.value if result.status is not None else "REJECTED",
            "reason_codes": tuple(code.value for code in result.reason_codes),
            "fingerprint": result.fingerprint,
        }
        return dataframe

    def populate_entry_trend(
        self, dataframe: DataFrame, metadata: dict[str, Any]
    ) -> DataFrame:
        # The scaffold is intentionally signal-free. Future signals must also
        # require alix_data_quality_valid before they can be emitted.
        dataframe["enter_long"] = 0
        dataframe["enter_tag"] = None
        return dataframe

    def populate_exit_trend(
        self, dataframe: DataFrame, metadata: dict[str, Any]
    ) -> DataFrame:
        dataframe["exit_long"] = 0
        dataframe["exit_tag"] = None
        return dataframe
